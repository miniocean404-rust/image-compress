/// ImageQuant PNG 有损压缩选项
///
/// ImageQuant 通过颜色量化将 PNG 转换为 8 位调色板图像，
/// 可以大幅减小文件大小（通常 50-80%），同时保持良好的视觉质量。
#[derive(Debug, Clone, Copy)]
pub struct ImageQuantOptions {
    /// 最小质量 `0..=100`
    ///
    /// 如果无法在此质量以上完成量化，将返回错误。
    /// 设置为 0 允许任何质量级别。
    ///
    /// 默认值: 0（允许任何质量）
    pub min_quality: u8,

    /// 最大质量 `0..=100`
    ///
    /// 目标质量上限。较低的值会尝试使用更少的颜色，
    /// 但颜色较少的图像并不总是更小（可能导致抖动增加）。
    ///
    /// - 100: 最高质量
    /// - 80-90: 高质量，人眼几乎无法察觉差异（推荐）
    /// - 60-80: 良好质量，轻微可见差异
    ///
    /// 默认值: 90（高质量压缩）
    pub max_quality: u8,

    /// 量化速度 `1..=10`
    ///
    /// - 1: 最慢，最高质量（推荐用于最终输出）
    /// - 3-4: 平衡速度和质量
    /// - 10: 最快，质量较低
    ///
    /// 默认值: 1（最高质量）
    pub speed: i32,

    /// 最小色阶化位数 `0..=4`
    ///
    /// 要忽略的最低有效位数。用于生成复古风格调色板。
    /// 值越大，颜色越少，压缩越小。
    ///
    /// - 0: 不进行色阶化（保留所有颜色细节）
    /// - 2: 轻微色阶化，通常不可见
    /// - 4: 明显色阶化，复古效果
    ///
    /// 默认值: 0（不进行色阶化，保持最佳质量）
    pub min_posterization: u8,

    /// 抖动级别 `0.0..=1.0`
    ///
    /// 抖动可以减少色带效应，但会增加文件大小。
    ///
    /// - 0.0: 无抖动，最小文件大小
    /// - 0.5: 中等抖动
    /// - 1.0: 完全抖动，最平滑的渐变
    ///
    /// 默认值: 0.8（良好的视觉质量和合理的文件大小平衡）
    pub dithering: f32,

    /// 输出 Gamma 值 `0.0..=1.0`
    ///
    /// 颜色从输入 Gamma 转换为此 Gamma。
    /// 默认值是 sRGB (~1/2.2 ≈ 0.45)。
    ///
    /// 默认值: 0.45455（标准 sRGB gamma）
    pub gamma: f64,

    /// 将透明颜色移动到调色板末尾
    ///
    /// 某些有缺陷的软件需要此选项，但会降低 PNG 压缩效率。
    ///
    /// 默认值: false（最佳压缩）
    pub last_index_transparent: bool,
}

impl Default for ImageQuantOptions {
    fn default() -> Self {
        ImageQuantOptions {
            // 允许任何质量级别，让算法自动选择最佳方案
            min_quality: 0,
            // 目标质量 85: 视觉无损阈值，在人眼难以察觉差异的前提下最大化压缩
            max_quality: 85,
            // 速度 1: 最慢但质量最高
            speed: 1,
            // 不进行色阶化，保持最佳颜色精度
            min_posterization: 0,
            // 抖动 0.75: 良好的视觉质量，减少色带效应，同时略微减小文件大小
            dithering: 0.75,
            // 标准 sRGB gamma 值
            gamma: 0.45455,
            // 不移动透明颜色，保持最佳压缩
            last_index_transparent: false,
        }
    }
}
